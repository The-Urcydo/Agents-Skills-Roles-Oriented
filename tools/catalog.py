#!/usr/bin/env python3
"""Generate SKILLS.md from the skill folders.

Usage:
  python3 tools/catalog.py           # write SKILLS.md
  python3 tools/catalog.py --check   # exit 1 if SKILLS.md is out of date
  python3 tools/catalog.py --root DIR
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib import FrontMatterError, parse_front_matter, read_text, repo_root

CATALOG = "SKILLS.md"
CATEGORY_ORDER = ("engineering", "productivity", "design", "repo")
CATEGORY_LABELS = {
    "engineering": "Engineering",
    "productivity": "Productivity",
    "design": "Design",
    "repo": "Repository",
    "uncategorized": "Uncategorized",
}


def skill_rows(root: Path) -> List[Dict[str, str]]:
    """One row per readable skill, sorted by folder name."""
    base = root / "skills"
    rows: List[Dict[str, str]] = []
    if not base.is_dir():
        return rows
    for entry in sorted(base.iterdir()):
        if entry.name.startswith(".") or entry.name == "README.md" or not entry.is_dir():
            continue
        sk = entry / "SKILL.md"
        if not sk.exists():
            continue
        try:
            fm, _ = parse_front_matter(read_text(sk))
        except FrontMatterError:
            continue
        if not isinstance(fm, dict):
            continue
        meta = fm.get("metadata") if isinstance(fm.get("metadata"), dict) else {}
        rows.append(
            {
                "name": str(fm.get("name") or entry.name).strip(),
                "description": " ".join(str(fm.get("description") or "").split()),
                "category": str(meta.get("category") or "uncategorized").strip(),
                "invocation": str(meta.get("invocation") or "both").strip(),
                "path": f"skills/{entry.name}/SKILL.md",
            }
        )
    return rows


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def render_catalog(root: Path) -> str:
    rows = skill_rows(root)
    lines = [
        "# Skills catalog",
        "",
        "<!-- Generated by tools/catalog.py. Do not edit. -->",
        "",
        f"{len(rows)} skill{'s' if len(rows) != 1 else ''}.",
        "",
    ]
    if not rows:
        lines.append("No skills yet.")
        lines.append("")
        return "\n".join(lines)

    groups: Dict[str, List[Dict[str, str]]] = {}
    for row in rows:
        groups.setdefault(row["category"], []).append(row)
    order = list(CATEGORY_ORDER) + sorted(k for k in groups if k not in CATEGORY_ORDER)
    for category in order:
        if category not in groups:
            continue
        lines.append(f"## {CATEGORY_LABELS.get(category, category.title())}")
        lines.append("")
        lines.append("| Skill | What it does | Invocation |")
        lines.append("|---|---|---|")
        for row in sorted(groups[category], key=lambda r: r["name"]):
            lines.append(
                f"| [`{row['name']}`]({row['path']}) | {_escape(row['description'])} | {row['invocation']} |"
            )
        lines.append("")
    return "\n".join(lines)


def write_catalog(root: Path) -> bool:
    """Write SKILLS.md if it changed. Returns True when the file changed."""
    path = root / CATALOG
    content = render_catalog(root)
    if path.exists() and read_text(path) == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true", help="exit 1 if SKILLS.md is out of date")
    ap.add_argument("--root", type=Path, default=None, help="repository root")
    args = ap.parse_args(argv)
    root = (args.root or repo_root()).resolve()
    path = root / CATALOG
    want = render_catalog(root)
    if args.check:
        if not path.exists():
            print(f"{CATALOG} is missing; run python3 tools/catalog.py")
            return 1
        if read_text(path) != want:
            print(f"{CATALOG} is out of date; run python3 tools/catalog.py")
            return 1
        print(f"{CATALOG} is up to date")
        return 0
    changed = write_catalog(root)
    print(f"{'wrote' if changed else 'unchanged'} {CATALOG}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
