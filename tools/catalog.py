#!/usr/bin/env python3
"""Generate SKILLS.md from the skill folders.

Usage:
  python3 tools/catalog.py           # write SKILLS.md
  python3 tools/catalog.py --check   # exit 1 if SKILLS.md is out of date
  python3 tools/catalog.py --root DIR
"""
from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib import CATEGORIES, FrontMatterError, parse_front_matter, read_text, repo_root, skill_folders

CATALOG = "SKILLS.md"
CATEGORY_ORDER = CATEGORIES
CATEGORY_LABELS = {
    "engineering": "Engineering",
    "productivity": "Productivity",
    "design": "Design",
    "repo": "Repository",
    "uncategorized": "Uncategorized",
}


@dataclass
class SkillRow:
    name: str
    description: str
    category: str
    invocation: str
    path: str


def read_skill_row(entry: Path) -> Optional[SkillRow]:
    try:
        fm, _ = parse_front_matter(read_text(entry / "SKILL.md"))
    except (FrontMatterError, OSError, UnicodeDecodeError):
        return None
    if not isinstance(fm, dict):
        return None
    meta = fm.get("metadata") if isinstance(fm.get("metadata"), dict) else {}
    return SkillRow(
        name=str(fm.get("name") or entry.name).strip(),
        description=" ".join(str(fm.get("description") or "").split()),
        category=str(meta.get("category") or "uncategorized").strip(),
        invocation=str(meta.get("invocation") or "both").strip(),
        path=f"skills/{entry.name}/SKILL.md",
    )


def skill_rows(root: Path) -> List[SkillRow]:
    """One row per readable skill, sorted by folder name."""
    rows: List[SkillRow] = []
    for entry in skill_folders(root):
        row = read_skill_row(entry)
        if row is not None:
            rows.append(row)
    return rows


def _escape_table_cell(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("[", "\\[")
        .replace("]", "\\]")
    )


def unreadable_skills(root: Path) -> List[str]:
    return [
        f"skills/{entry.name}/SKILL.md"
        for entry in skill_folders(root)
        if read_skill_row(entry) is None
    ]


def render_catalog(root: Path) -> str:
    rows = skill_rows(root)
    lines = [
        "# Skills catalog",
        "",
        "<!-- Generated by tools/catalog.py. Do not edit. -->",
        "",
        f"{len(rows)} skill{'s' if len(rows) != 1 else ''}.",
        "",
    ]
    if not rows:
        lines.append("No skills yet.")
        lines.append("")
        return "\n".join(lines)

    groups: Dict[str, List[SkillRow]] = {}
    for row in rows:
        groups.setdefault(row.category, []).append(row)
    order = list(CATEGORY_ORDER) + sorted(k for k in groups if k not in CATEGORY_ORDER)
    for category in order:
        if category not in groups:
            continue
        lines.append(f"## {CATEGORY_LABELS.get(category, category.title())}")
        lines.append("")
        lines.append("| Skill | What it does | Invocation |")
        lines.append("|---|---|---|")
        for row in sorted(groups[category], key=lambda r: r.name):
            lines.append(
                f"| [`{row.name}`]({row.path}) | {_escape_table_cell(row.description)} | {row.invocation} |"
            )
        lines.append("")
    return "\n".join(lines)


def read_catalog(path: Path) -> Optional[str]:
    """Return the catalog text, or None when the file does not exist.

    Raises OSError when the file exists but cannot be read as UTF-8 text.
    """
    if not (path.exists() or path.is_symlink()):
        return None
    try:
        return read_text(path)
    except (OSError, UnicodeDecodeError) as exc:
        raise OSError(f"cannot read {path.name}: {exc}") from exc


def write_catalog(root: Path) -> bool:
    """Write SKILLS.md if it changed. Returns True when the file changed."""
    path = root / CATALOG
    content = render_catalog(root)
    if read_catalog(path) == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true", help="exit 1 if SKILLS.md is out of date")
    ap.add_argument("--root", type=Path, default=None, help="repository root")
    args = ap.parse_args(argv)
    root = (args.root or repo_root()).expanduser().resolve()
    path = root / CATALOG
    bad = unreadable_skills(root)
    if bad:
        for bad_path in bad:
            print(f"{bad_path}: unreadable front matter")
        return 1
    if args.check:
        try:
            current = read_catalog(path)
        except OSError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        want = render_catalog(root)
        if current is None:
            print(f"{CATALOG} is missing; run python3 tools/catalog.py")
            return 1
        if current != want:
            print(f"{CATALOG} is out of date; run python3 tools/catalog.py")
            return 1
        print(f"{CATALOG} is up to date")
        return 0
    try:
        changed = write_catalog(root)
    except OSError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(f"{'wrote' if changed else 'unchanged'} {CATALOG}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
