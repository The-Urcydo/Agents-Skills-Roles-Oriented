#!/usr/bin/env python3
"""Generate roles/ROSTER.md from role charters.

Usage:
  python3 tools/roster.py           # write roles/ROSTER.md
  python3 tools/roster.py --check   # exit 1 if the roster is out of date
  python3 tools/roster.py --root DIR
"""
from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib import (
    ROLE_FIELDS,
    TIERS,
    FrontMatterError,
    parse_front_matter,
    read_text,
    repo_root,
    role_folders,
)

ROSTER = "roles/ROSTER.md"
TIER_LABELS = {"flow": "Flow", "advisory": "Advisory", "optional": "Optional"}


@dataclass
class RoleRow:
    name: str
    folder: str
    tier: str
    mission: str
    skills: List[str]


def read_role_row(entry: Path) -> Optional[RoleRow]:
    try:
        fm, _ = parse_front_matter(read_text(entry / "ROLE.md"))
    except (FrontMatterError, OSError, UnicodeDecodeError):
        return None
    if not isinstance(fm, dict):
        return None
    if any(key not in fm for key in ROLE_FIELDS):
        return None
    role = fm.get("role")
    tier = fm.get("tier")
    mission = fm.get("mission")
    raw_skills = fm.get("skills")
    if not isinstance(role, str) or not role.strip():
        return None
    if not isinstance(tier, str) or tier.strip() not in TIERS:
        return None
    if not isinstance(mission, str) or not mission.strip():
        return None
    if not isinstance(raw_skills, list) or not all(
        isinstance(item, str) and item.strip() for item in raw_skills
    ):
        return None
    return RoleRow(
        name=role.strip(),
        folder=entry.name,
        tier=tier.strip(),
        mission=" ".join(mission.split()),
        skills=[item.strip() for item in raw_skills],
    )


def unreadable_roles(root: Path) -> List[str]:
    return [
        f"roles/{entry.name}/ROLE.md"
        for entry in role_folders(root)
        if read_role_row(entry) is None
    ]


def _escape_table_cell(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("[", "\\[")
        .replace("]", "\\]")
    )


def render_roster(root: Path) -> str:
    rows = [row for entry in role_folders(root) if (row := read_role_row(entry)) is not None]
    lines = [
        "# Role roster",
        "",
        "<!-- Generated by tools/roster.py. Do not edit. -->",
        "",
        f"{len(rows)} role{'s' if len(rows) != 1 else ''}.",
        "",
    ]
    if not rows:
        lines.append("No roles yet.")
        lines.append("")
        return "\n".join(lines)

    groups: Dict[str, List[RoleRow]] = {}
    for row in rows:
        groups.setdefault(row.tier, []).append(row)
    for tier in TIERS:
        if tier not in groups:
            continue
        lines.append(f"## {TIER_LABELS[tier]}")
        lines.append("")
        lines.append("| Role | Mission | Skills |")
        lines.append("|---|---|---|")
        for row in sorted(groups[tier], key=lambda item: item.name):
            skills = ", ".join(
                f"[`{name}`](../skills/{name}/SKILL.md)" for name in row.skills
            ) or "—"
            lines.append(
                f"| [`{row.name}`]({row.folder}/ROLE.md) "
                f"| {_escape_table_cell(row.mission)} | {skills} |"
            )
        lines.append("")

    used: Dict[str, List[str]] = {}
    for row in rows:
        for name in row.skills:
            used.setdefault(name, []).append(row.name)
    shared = {name: names for name, names in used.items() if len(names) > 1}
    if shared:
        lines.append("## Shared skills")
        lines.append("")
        lines.append("Skills used by more than one role.")
        lines.append("")
        lines.append("| Skill | Used by |")
        lines.append("|---|---|")
        for name in sorted(shared):
            lines.append(
                f"| [`{name}`](../skills/{name}/SKILL.md) "
                f"| {', '.join(sorted(shared[name]))} |"
            )
        lines.append("")
    return "\n".join(lines)


def read_roster(path: Path) -> Optional[str]:
    """Return the roster text, or None when the file does not exist."""
    if not (path.exists() or path.is_symlink()):
        return None
    try:
        return read_text(path)
    except (OSError, UnicodeDecodeError) as exc:
        raise OSError(f"cannot read {path.name}: {exc}") from exc


def write_roster(root: Path) -> bool:
    """Write roles/ROSTER.md if it changed. Returns True when the file changed."""
    path = root / ROSTER
    content = render_roster(root)
    if read_roster(path) == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true", help="exit 1 if the roster is out of date")
    ap.add_argument("--root", type=Path, default=None, help="repository root")
    args = ap.parse_args(argv)
    root = (args.root or repo_root()).expanduser().resolve()
    path = root / ROSTER

    bad = unreadable_roles(root)
    if bad:
        for bad_path in bad:
            print(f"{bad_path}: unreadable front matter")
        return 1

    if args.check:
        try:
            current = read_roster(path)
        except OSError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        want = render_roster(root)
        if current is None:
            print(f"{ROSTER} is missing; run python3 tools/roster.py")
            return 1
        if current != want:
            print(f"{ROSTER} is out of date; run python3 tools/roster.py")
            return 1
        print(f"{ROSTER} is up to date")
        return 0

    try:
        changed = write_roster(root)
    except OSError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(f"{'wrote' if changed else 'unchanged'} {ROSTER}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
